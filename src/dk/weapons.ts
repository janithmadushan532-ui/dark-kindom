export const WEAPON_MAP: Record<WeaponId, WeaponDefinition> = WEAPONS.reduce(
  (acc, w) => {
    acc[w.id] = w;
    return acc;
  },
  {} as Record<WeaponId, WeaponDefinition>
);

export function getWeaponQualityTier(weaponId: WeaponId): WeaponQualityTier {
  return WEAPON_MAP[weaponId]?.tier ?? 'basic';
}

export function getWeaponMcqRequirement(weaponId: WeaponId): 3 | 4 {
  return getWeaponQualityTier(weaponId) === 'premium' ? 4 : 3;
}
